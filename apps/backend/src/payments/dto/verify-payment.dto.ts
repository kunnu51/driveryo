import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString } from 'class-validator';

export class VerifyPaymentDto {
  @ApiProperty({
    example: 'order_HYD_987654321',
    description: 'Razorpay order ID returned during checkout creation',
  })
  @IsNotEmpty()
  @IsString()
  razorpayOrderId: string;

  @ApiProperty({
    example: 'pay_HYD_123456789',
    description: 'Razorpay payment ID returned after successful customer authorization',
  })
  @IsNotEmpty()
  @IsString()
  razorpayPaymentId: string;

  @ApiProperty({
    example: 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855',
    description: 'HMAC SHA256 signature generated by Razorpay',
  })
  @IsNotEmpty()
  @IsString()
  razorpaySignature: string;
}
